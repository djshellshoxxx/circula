#!/usr/bin/env bash
# ARC-024: dependency licence manifest and approved-list check.
#
#   scripts/licenses.sh            write docs/legal/DEPENDENCIES.md from the modules linked into the binary
#   scripts/licenses.sh --check    fail if a linked module has a licence outside docs/legal/license-allowlist.txt,
#                                  or if the committed manifest is out of date
#
# Modules are those that go list reports for ./cmd/circula and its tests' non-test closure (what ships). The licence
# is identified from the module's LICENSE file text; anything not recognised is reported as UNKNOWN and fails the check.
set -euo pipefail

cd "$(dirname "$0")/.."
GO="${GO:-go}"
OUT=docs/legal/DEPENDENCIES.md
ALLOW=docs/legal/license-allowlist.txt

classify() {
  local text
  text="$(head -c 6000 "$1" | tr '\n' ' ' | tr -s ' ')"
  case "$text" in
    *"Apache License"*"Version 2.0"*) echo "Apache-2.0" ;;
    *"Mozilla Public License"*"2.0"*) echo "MPL-2.0" ;;
    *"Permission is hereby granted, free of charge"*) echo "MIT" ;;
    *"Redistribution and use in source and binary forms"*"Neither the name"*|*"Redistributions of source code must retain"*"Neither the name"*) echo "BSD-3-Clause" ;;
    *"Redistribution and use in source and binary forms"*) echo "BSD-2-Clause" ;;
    *"Permission to use, copy, modify, and/or distribute this software for any purpose with or without fee"*) echo "ISC" ;;
    *) echo "UNKNOWN" ;;
  esac
}

rows="$(mktemp)"
trap 'rm -f "$rows"' EXIT
"$GO" list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}}|{{.Version}}|{{.Dir}}{{end}}{{end}}' ./cmd/circula |
  sort -u | while IFS='|' read -r path version dir; do
    [ -n "$path" ] || continue
    file="$(find "$dir" -maxdepth 1 -type f \( -iname 'licen[cs]e*' -o -iname 'copying*' \) | sort | head -1)"
    if [ -z "$file" ]; then lic="UNKNOWN"; else lic="$(classify "$file")"; fi
    echo "| \`$path\` | $version | $lic |"
  done >"$rows"

gen() {
  cat <<'EOF'
# Dependency licence manifest

Specification: ARC-024. Generated by `scripts/licenses.sh`; do not edit by hand. Lists every third-party module
linked into the `circula` binary, its pinned version (`go.mod`), and its licence identified from the module's licence
file. `scripts/licenses.sh --check` (run in CI) fails when a licence is not in
[license-allowlist.txt](license-allowlist.txt) or this file is stale. The licence of the product itself is undecided
(DEC-004); this manifest records what that decision must be compatible with.

| Module | Version | Licence (SPDX) |
|---|---|---|
EOF
  cat "$rows"
}

if [ "${1:-}" = "--check" ]; then
  fail=0
  while IFS='|' read -r _ mod _ lic _; do
    lic="$(echo "$lic" | tr -d ' ')"
    if ! grep -qxF "$lic" "$ALLOW"; then
      echo "licence $lic of $mod is not on the approved list ($ALLOW)" >&2
      fail=1
    fi
  done <"$rows"
  tmp="$(mktemp)"
  gen >"$tmp"
  if ! diff -q "$tmp" "$OUT" >/dev/null 2>&1; then
    echo "$OUT is out of date; run scripts/licenses.sh" >&2
    fail=1
  fi
  rm -f "$tmp"
  [ "$fail" -eq 0 ] && echo "dependency licences: ok"
  exit "$fail"
fi

mkdir -p docs/legal
gen >"$OUT"
echo "wrote $OUT"
