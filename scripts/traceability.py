#!/usr/bin/env python3
"""QA-042: regenerate docs/TRACEABILITY.md from the specs, the code and the tests.

Sources, in order of authority:
  * status tables in docs/specs/NN-*.md (`| ID | Priority | Status | Note |`):
    priority, status and note of every requirement ID;
  * the code and test citations already in docs/TRACEABILITY.md (curated), each
    checked against the tree: a cited file must exist, a cited symbol must occur
    in it, a cited Go test must be declared in it;
  * Go test functions whose doc comment (or name) names the ID (discovered).

Rows in the matrix with no status table (the API-* operations of 07) keep their
curated status and note; their citations are checked the same way.

  --write  rewrite docs/TRACEABILITY.md
  --check  exit 1 if the file differs from what --write would produce
  (none)   print a JSON report: added rows, stale citations, built rows without tests

Output is deterministic: no timestamps, no SHAs, stable order.
"""
import argparse
import difflib
import json
import os
import re
import sys
from pathlib import Path

SPECS = "docs/specs"
TRACE = "docs/TRACEABILITY.md"
ID_RE = r"(?:[A-Z]{2,8}-\d{3}|LED-\d+)"
ID_CELL = re.compile(r"^\|\s*(%s)\s*\|" % ID_RE)
ID_ANY = re.compile(r"\b(%s)\b" % ID_RE)
STATUS_HEADER = re.compile(r"^\|\s*ID\s*\|\s*Priority\s*\|\s*Status\s*\|")
HEADING = re.compile(r"^#{2,4}\s+(%s)\s*·\s*[^·]*·\s*(.+?)\s*$" % ID_RE)
DEFINITION = re.compile(r"^\s*[-*]\s+\**(%s)\**\s*[:.]\s*(.+)$" % ID_RE)
SECTION = re.compile(r"^##\s+(\d\d)\b")
CITE = re.compile(r"^`([^`]+)`(?:\s*\((.+)\))?$")
GO_TEST = re.compile(r"^func\s+(?:\([^)]*\)\s*)?((?:Test|Fuzz|Benchmark|Example)\w*)\s*\(")
COLUMNS = "| ID | Pri | Requirement (short) | Status | Code path(s) | Test name(s) | Note |"
RULE = "|---|---|---|---|---|---|---|"
TITLE_MAX = 90
SKIP_DIRS = {".git", "node_modules", "vendor", "bin", "testdata"}

HEADER = """# Traceability matrix

Generated by `scripts/traceability.py` (QA-042). Do not edit this file by hand: change the spec, the code or the
tests, then run `python3 scripts/traceability.py --write`. CI runs `--check`, which fails when this file is out of
date or cites a file, symbol or test that no longer exists.

Sources: the status tables in [`docs/specs/`](specs/) give each ID's priority, status and note; the code and test
citations are curated in this file and checked against the tree on every run; Go test functions whose doc comment
names an ID are added to its row. Rows with no status table (the API operations of 07) keep their recorded status.
A citation proves that the code or test exists. It does not prove that the test passes at a given build: CI does.

## Status values

- **built**: behaviour exists in the code and at least one test or observed run covers it (test names listed).
- **partial**: exists with the gaps stated in the note.
- **not built**: no implementation.
- **deferred**: out of MVP by the spec or by a recorded decision.
- Decision-register rows (DEC-*) use decision states: decided, open or deferred. The owner decisions are in
  [DECISIONS.md](DECISIONS.md).
"""


def cells(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def read(path):
    return path.read_text(encoding="utf-8")


def spec_files(root):
    files = sorted((root / SPECS).glob("[0-1][0-9]-*.md"))
    if not files:
        raise ValueError("no numbered specification files found under %s" % SPECS)
    return files


def parse_specs(root):
    """Return (status rows by ID, section order, titles, section titles)."""
    status, order, titles, alt_titles, sec_titles = {}, {}, {}, {}, {}
    for f in spec_files(root):
        sec = f.name[:2]
        order.setdefault(sec, [])
        in_status = False
        header = None
        for line in read(f).splitlines():
            if line.startswith("# ") and sec not in sec_titles:
                sec_titles[sec] = line[2:].strip()
            m = HEADING.match(line)
            if m:
                titles.setdefault(m.group(1), m.group(2))
            m = DEFINITION.match(line)
            if m:
                alt_titles.setdefault(m.group(1), m.group(2))
            if line.startswith("|"):
                if header is None:
                    header = cells(line)
                    in_status = bool(STATUS_HEADER.match(line))
                    continue
                m = ID_CELL.match(line)
                if not m:
                    continue
                c = cells(line)
                rid = m.group(1)
                if in_status:
                    if rid in status:
                        raise ValueError("%s has two status rows (%s, %s)" % (rid, status[rid]["spec"], f.name))
                    status[rid] = {"pri": c[1], "status": c[2], "note": c[3] if len(c) > 3 else "",
                                   "spec": f.name, "sec": sec}
                    order[sec].append(rid)
                elif len(c) > 1 and header and len(header) > 1:
                    alt_titles.setdefault(rid, c[1])
            else:
                header = None
                in_status = False
    for rid, t in alt_titles.items():
        titles.setdefault(rid, t)
    return status, order, titles, sec_titles


def parse_matrix(root):
    """Return (rows by ID, section of each row, section headings, matrix-only order)."""
    path = root / TRACE
    if not path.is_file():
        raise ValueError("traceability matrix missing: %s" % TRACE)
    rows, where, headings, order = {}, {}, {}, {}
    sec = None
    for line in read(path).splitlines():
        m = SECTION.match(line)
        if m:
            sec = m.group(1)
            headings[sec] = line[3:].strip()
            order.setdefault(sec, [])
            continue
        m = ID_CELL.match(line)
        if m and sec is not None:
            c = cells(line)
            while len(c) < 7:
                c.append("-")
            rows[m.group(1)] = c
            where[m.group(1)] = sec
            order[sec].append(m.group(1))
    return rows, where, headings, order


class Tree:
    """Lazy view of the repository used to check citations."""

    def __init__(self, root):
        self.root = root
        self.cache = {}
        self.discovered = {}
        self._scan_tests()

    def text(self, rel):
        if rel not in self.cache:
            p = self.root / rel
            self.cache[rel] = read(p) if p.is_file() else None
        return self.cache[rel]

    def exists(self, rel):
        return (self.root / rel).exists()

    def has_symbol(self, rel, sym):
        t = self.text(rel)
        if t is None:
            return False
        return re.search(r"(?<![\w])%s(?![\w])" % re.escape(sym), t) is not None

    def has_test(self, rel, name):
        t = self.text(rel)
        if t is None:
            return False
        if rel.endswith(".go"):
            return re.search(r"^func\s+(?:\([^)]*\)\s*)?%s\s*\(" % re.escape(name), t, re.M) is not None
        return name in t

    def _scan_tests(self):
        for dirpath, dirnames, filenames in os.walk(self.root):
            dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
            for fn in sorted(filenames):
                if not fn.endswith("_test.go"):
                    continue
                rel = Path(dirpath, fn).relative_to(self.root).as_posix()
                comment = []
                for line in read(Path(dirpath, fn)).splitlines():
                    s = line.strip()
                    if s.startswith("//"):
                        comment.append(s)
                        continue
                    m = GO_TEST.match(line)
                    if m:
                        ids = set(ID_ANY.findall(" ".join(comment) + " " + m.group(1)))
                        for rid in ids:
                            self.discovered.setdefault(rid, set()).add("%s:%s" % (rel, m.group(1)))
                    comment = []


def split(cell):
    if cell in ("", "-"):
        return []
    return [p.strip() for p in cell.split("<br>") if p.strip()]


def check_code(tree, item):
    m = CITE.match(item)
    if not m:
        return True
    path, sym = m.group(1), m.group(2)
    if not tree.exists(path):
        return False
    if sym and (tree.root / path).is_file():
        return all(tree.has_symbol(path, s.strip()) for s in sym.split(",") if s.strip())
    return True


def check_test(tree, item):
    m = CITE.match(item)
    if not m:
        return True
    ref = m.group(1)
    if ":" in ref:
        path, name = ref.split(":", 1)
        return tree.has_test(path, name)
    return tree.exists(ref)


def esc(s):
    return s.replace("|", "\\|")


def generate(root):
    root = Path(root)
    status, sorder, titles, sec_titles = parse_specs(root)
    mrows, mwhere, mheadings, morder = parse_matrix(root)
    tree = Tree(root)
    report = {"added": [], "stale": [], "built_without_tests": []}

    sections = sorted(set(sorder) | set(morder))
    out = [HEADER.rstrip("\n"), ""]
    counts = {}
    body = []
    for sec in sections:
        ids = list(sorder.get(sec, []))
        ids += [r for r in morder.get(sec, []) if r not in status]
        if not ids:
            continue
        heading = mheadings.get(sec) or sec_titles.get(sec) or sec
        body += ["", "## " + heading, "", COLUMNS, RULE]
        for rid in ids:
            old = mrows.get(rid)
            if old is None:
                report["added"].append(rid)
            st = status.get(rid)
            pri = st["pri"] if st else old[1]
            title = old[2] if old and old[2] not in ("", "-") else titles.get(rid, "-")
            title = esc(title)
            if len(title) > TITLE_MAX and not old:
                title = title[:TITLE_MAX].rstrip()
            state = st["status"] if st else old[3]
            note = st["note"] if st else old[6]
            code, tests = [], []
            for item in split(old[4]) if old else []:
                if check_code(tree, item):
                    code.append(item)
                else:
                    report["stale"].append("%s code %s" % (rid, item))
            for item in split(old[5]) if old else []:
                if check_test(tree, item):
                    tests.append(item)
                else:
                    report["stale"].append("%s test %s" % (rid, item))
            seen = {CITE.match(t).group(1) if CITE.match(t) else t for t in tests}
            for ref in sorted(tree.discovered.get(rid, ())):
                if ref not in seen:
                    tests.append("`%s`" % ref)
            if not rid.startswith("DEC-"):
                counts[state] = counts.get(state, 0) + 1
                if state == "built" and not tests:
                    report["built_without_tests"].append(rid)
            body.append("| %s | %s | %s | %s | %s | %s | %s |" % (
                rid, pri, title, state, "<br>".join(code) or "-", "<br>".join(tests) or "-", note or "-"))
    summary = ", ".join("%s %d" % (k, counts[k]) for k in sorted(counts))
    out.append("Counts (all rows except DEC-*): %s." % summary)
    out += body
    return "\n".join(out) + "\n", report


def check(root):
    root = Path(root)
    want, _ = generate(root)
    have = read(root / TRACE)
    if want == have:
        return []
    return list(difflib.unified_diff(have.splitlines(), want.splitlines(), TRACE, TRACE + " (generated)",
                                     lineterm="", n=0))


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--root", default=".", help="repository root")
    g = p.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true", help="rewrite the matrix")
    g.add_argument("--check", action="store_true", help="exit 1 if the matrix is out of date")
    a = p.parse_args()
    root = Path(a.root)
    try:
        if a.check:
            diff = check(root)
            if diff:
                sys.stderr.write("%s is out of date or cites missing code/tests; run "
                                 "python3 scripts/traceability.py --write\n" % TRACE)
                sys.stderr.write("\n".join(diff[:60]) + "\n")
                raise SystemExit(1)
            print("traceability: ok")
            return
        text, report = generate(root)
        if a.write:
            (root / TRACE).write_text(text, encoding="utf-8")
        print(json.dumps({k: (len(v) if a.write else v) for k, v in report.items()}, indent=2, sort_keys=True))
    except (ValueError, OSError) as exc:
        p.error(str(exc))


if __name__ == "__main__":
    main()
