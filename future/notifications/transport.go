package notifications

import (
	"context"
	"errors"
	"time"
)

// Fixed, privacy-minimal wording. Every member-activity notification uses
// exactly these strings whatever the kind: providers never see amounts, names,
// counterparties, proposal text or even which kind of event occurred.
const (
	GenericSubject = "New Circula activity"
	PushTitle      = "Circula"
	PushOpenPath   = "/notifications" // relative; resolved by the service worker against its own origin
	PushTag        = "circula-activity"
	VerifySubject  = "Confirm your Circula email notifications"
)

// EmailMessage is a fully formed outbound message. SMTP details (From, host,
// TLS, auth) are operator configuration inside the sender, never part of the
// message and never member-controlled.
type EmailMessage struct {
	To             string
	Subject        string
	Body           string
	UnsubscribeURL string // https one-click URL (RFC 8058); empty for the verification message
	MessageID      string // generated by the dispatcher; recorded as provider_message_id
}

// EmailSender sends one message. Implementations must be safe for concurrent
// use, honour ctx, require verified TLS, and never log message content.
type EmailSender interface {
	SendEmail(ctx context.Context, m EmailMessage) error
}

// PushMessage is one Web Push request: a fixed payload for one subscription.
type PushMessage struct {
	Endpoint string
	P256dh   string
	Auth     string
	Payload  []byte
	TTL      time.Duration
	Topic    string
}

// PushSender sends one Web Push message.
type PushSender interface {
	SendPush(ctx context.Context, m PushMessage) error
}

// SendClass classifies a failed send.
type SendClass int

const (
	// ClassTransient: retry with backoff (network error, 4xx SMTP, push 5xx).
	ClassTransient SendClass = iota
	// ClassRateLimited: retry no sooner than RetryAfter (capped).
	ClassRateLimited
	// ClassPermanent: this message cannot be delivered; do not retry.
	ClassPermanent
	// ClassTargetGone: the destination is permanently invalid (SMTP 5xx on
	// RCPT, push 404/410). The target is disabled.
	ClassTargetGone
)

func (c SendClass) String() string {
	return [...]string{"transient", "rate_limited", "permanent", "target_gone"}[c]
}

// SendError is the only error shape senders return. Code is a fixed
// vocabulary word; the underlying cause is deliberately not rendered because
// provider error text can echo addresses, endpoints and tokens.
type SendError struct {
	Class      SendClass
	Code       string
	RetryAfter time.Duration
	cause      error
}

// NewSendError builds a SendError; cause is kept for errors.Is on context
// errors only and never appears in Error().
func NewSendError(class SendClass, code string, retryAfter time.Duration, cause error) *SendError {
	return &SendError{Class: class, Code: code, RetryAfter: retryAfter, cause: cause}
}

func (e *SendError) Error() string { return "send failed: " + e.Class.String() + ": " + e.Code }

// Unwrap exposes only context cancellation/deadline causes.
func (e *SendError) Unwrap() error {
	if errors.Is(e.cause, context.Canceled) {
		return context.Canceled
	}
	if errors.Is(e.cause, context.DeadlineExceeded) {
		return context.DeadlineExceeded
	}
	return nil
}

// MaxRetryAfter caps provider-supplied Retry-After values.
const MaxRetryAfter = time.Hour

func classify(err error) *SendError {
	var se *SendError
	if errors.As(err, &se) {
		return se
	}
	return NewSendError(ClassTransient, "unknown", 0, err)
}
