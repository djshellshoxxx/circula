package governance

import (
	"bytes"
	"encoding/json"
	"errors"
	"io"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"
)

// The bounded parser pattern is adapted from this repository's isolated messaging
// audit. It is local code, not an import or dependency on another future module.
func strictDecode(raw []byte, out any) error {
	if len(raw) == 0 || len(raw) > 131072 || !utf8.Valid(raw) || !validJSONUnicodeEscapes(raw) || !uniqueJSONNames(raw) {
		return errors.New("invalid governance JSON")
	}
	decoder := json.NewDecoder(bytes.NewReader(raw))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(out); err != nil {
		return err
	}
	var extra any
	if decoder.Decode(&extra) != io.EOF {
		return errors.New("trailing governance JSON")
	}
	return nil
}

// JSON permits UTF-16 escapes; reject unpaired surrogates rather than letting
// encoding/json silently replace them before policy validation.
func validJSONUnicodeEscapes(raw []byte) bool {
	for i := 0; i < len(raw); {
		if raw[i] != '\\' {
			i++
			continue
		}
		if i+1 >= len(raw) {
			return false
		}
		if raw[i+1] != 'u' {
			i += 2
			continue
		}
		if i+6 > len(raw) {
			return false
		}
		value, err := strconv.ParseUint(string(raw[i+2:i+6]), 16, 16)
		if err != nil {
			return false
		}
		if value >= 0xD800 && value <= 0xDBFF {
			if i+12 > len(raw) || raw[i+6] != '\\' || raw[i+7] != 'u' {
				return false
			}
			low, err := strconv.ParseUint(string(raw[i+8:i+12]), 16, 16)
			if err != nil || low < 0xDC00 || low > 0xDFFF {
				return false
			}
			i += 12
			continue
		}
		if value >= 0xDC00 && value <= 0xDFFF {
			return false
		}
		i += 6
	}
	return true
}

// uniqueJSONNames rejects ambiguous duplicate names, including case aliases
// that encoding/json otherwise maps to the same Go field. Depth is bounded.
func uniqueJSONNames(raw []byte) bool {
	decoder := json.NewDecoder(bytes.NewReader(raw))
	var value func(int) bool
	value = func(depth int) bool {
		if depth > 16 {
			return false
		}
		token, err := decoder.Token()
		if err != nil {
			return false
		}
		delimiter, container := token.(json.Delim)
		if !container {
			return true
		}
		switch delimiter {
		case '{':
			seen := map[string]bool{}
			for decoder.More() {
				key, err := decoder.Token()
				if err != nil {
					return false
				}
				name, ok := key.(string)
				if !ok {
					return false
				}
				name = jsonNameKey(name)
				if seen[name] {
					return false
				}
				seen[name] = true
				if !value(depth + 1) {
					return false
				}
			}
			end, err := decoder.Token()
			return err == nil && end == json.Delim('}')
		case '[':
			for decoder.More() {
				if !value(depth + 1) {
					return false
				}
			}
			end, err := decoder.Token()
			return err == nil && end == json.Delim(']')
		default:
			return false
		}
	}
	if !value(0) {
		return false
	}
	_, err := decoder.Token()
	return err == io.EOF
}

// jsonNameKey matches encoding/json's Unicode simple-fold field equivalence.
// It is only a comparison key: input names and valid single aliases are not
// rewritten, and distinct names requiring multi-rune expansions stay distinct.
func jsonNameKey(name string) string {
	return strings.Map(func(r rune) rune {
		least := r
		for folded := unicode.SimpleFold(r); folded != r; folded = unicode.SimpleFold(folded) {
			if folded < least {
				least = folded
			}
		}
		return least
	}, name)
}
