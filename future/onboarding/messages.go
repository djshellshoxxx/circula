import "strings"

// Message catalogs. Strings are plain text and are always HTML-escaped by the
// templates. The French catalog is an author draft: it needs review by a
// native speaker before any release (see AUDIT.md).
var catalogs = map[string]map[string]string{"en": en, "fr": fr}

// Locales lists supported locale tags.
func Locales() []string { return []string{"en", "fr"} }

func pickLocale(tag string) string {
	tag = strings.ToLower(tag)
	if i := strings.IndexAny(tag, "-_"); i > 0 {
		tag = tag[:i]
	}
	if _, ok := catalogs[tag]; ok {
		return tag
	}
	return "en"
}

